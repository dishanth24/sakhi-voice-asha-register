export function useTranslation() {
  const language = useAppStore((s) => s.language);

  const t = useCallback(
    (key) => {
      const lang = translationData[language] || translationData.en;
      return lang[key] || translationData.en[key] || key;
    },
    [language]
  );

  return { t, language };
}
